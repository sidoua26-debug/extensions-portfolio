#!/usr/bin/env node
/**
 * scripts/build_worker.mjs
 * Bundles the Word-to-LaTeX Web Worker and Client Controller.
 * Resolves pandoc-wasm, browser_wasi_shim, and fflate from the local workspace.
 */

import path from 'node:path';
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PORTFOLIO_ROOT = path.resolve(__dirname, '..');

// Locate node_modules: check explicit env var override first, then local portfolio packages
function findNodeModules() {
  const candidates = [
    process.env.NODE_MODULES_DIR,
    path.resolve(PORTFOLIO_ROOT, 'node_modules'),
  ].filter(Boolean);

  for (const candidate of candidates) {
    if (fs.existsSync(candidate) && fs.existsSync(path.join(candidate, 'esbuild'))) {
      return candidate;
    }
  }
  return null;
}

const NODE_MODULES = findNodeModules();

if (!NODE_MODULES) {
  console.error('Error: Required build-time dependencies not found.');
  console.error('To build the worker bundle, node_modules containing esbuild, pandoc-wasm,');
  console.error('@bjorn3/browser_wasi_shim, and fflate are required.');
  console.error('You can provide the path via NODE_MODULES_DIR=/path/to/node_modules');
  process.exit(1);
}

const require = createRequire(import.meta.url);
const esbuildPath = path.resolve(NODE_MODULES, 'esbuild/lib/main.js');

if (!fs.existsSync(esbuildPath)) {
  console.error(`Error: esbuild entry not found at ${esbuildPath}`);
  process.exit(1);
}

const esbuild = require(esbuildPath);

const WORKER_ENTRY = path.resolve(PORTFOLIO_ROOT, 'src/converter/worker.ts');
const CLIENT_ENTRY = path.resolve(PORTFOLIO_ROOT, 'src/converter/client.ts');
const UI_ENTRY = path.resolve(PORTFOLIO_ROOT, 'src/converter/ui.ts');
const OUT_DIR = path.resolve(PORTFOLIO_ROOT, 'assets/js');
const WORKER_OUT = path.resolve(OUT_DIR, 'converter.worker.js');
const CLIENT_OUT = path.resolve(OUT_DIR, 'converterClient.js');
const UI_OUT = path.resolve(OUT_DIR, 'converterUi.js');

fs.mkdirSync(OUT_DIR, { recursive: true });

console.log('Building Word-to-LaTeX assets:');
console.log(`  Worker Entry: ${WORKER_ENTRY} -> ${WORKER_OUT}`);
console.log(`  Client Entry: ${CLIENT_ENTRY} -> ${CLIENT_OUT}`);
console.log(`  UI Entry:     ${UI_ENTRY} -> ${UI_OUT}`);

// Custom plugin to resolve pandoc-wasm unexported core.js and packages
const resolveWorkspaceModules = {
  name: 'resolve-workspace-modules',
  setup(build) {
    build.onResolve({ filter: /^pandoc-wasm\/src\/core\.js$/ }, () => ({
      path: path.join(NODE_MODULES, 'pandoc-wasm/src/core.js'),
    }));

    build.onResolve({ filter: /^@bjorn3\/browser_wasi_shim/ }, (args) => {
      const subpath = args.path.replace(/^@bjorn3\/browser_wasi_shim/, '');
      const fullPath = subpath
        ? path.join(NODE_MODULES, '@bjorn3/browser_wasi_shim', subpath)
        : path.join(NODE_MODULES, '@bjorn3/browser_wasi_shim/dist/index.js');
      return { path: fullPath };
    });

    build.onResolve({ filter: /^fflate$/ }, () => ({
      path: path.join(NODE_MODULES, 'fflate/esm/browser.js'),
    }));
  },
};

try {
  // 1. Build Worker Bundle (IIFE for web worker thread)
  await esbuild.build({
    entryPoints: [WORKER_ENTRY],
    outfile: WORKER_OUT,
    bundle: true,
    format: 'iife',
    target: ['es2022'],
    minify: false,
    sourcemap: false,
    plugins: [resolveWorkspaceModules],
    banner: {
      js: `/*
 * Word-to-LaTeX In-Browser Web Worker Bundle
 * Generated by scripts/build_worker.mjs
 * Includes pandoc-wasm core, @bjorn3/browser_wasi_shim, fflate, and LaTeX cleanup pipeline.
 * Licenses: GPL-2.0+ (Pandoc WASM), MIT (pandoc-wasm wrapper, fflate), Apache-2.0/MIT (browser_wasi_shim).
 */`,
    },
  });

  const workerStat = fs.statSync(WORKER_OUT);
  console.log(`✓ Worker bundled: ${WORKER_OUT} (${(workerStat.size / 1024).toFixed(1)} KB)`);

  // 2. Build Client Controller (ESM for main thread consumption)
  await esbuild.build({
    entryPoints: [CLIENT_ENTRY],
    outfile: CLIENT_OUT,
    bundle: true,
    format: 'esm',
    target: ['es2022'],
    minify: false,
    sourcemap: false,
    banner: {
      js: `/*
 * Word-to-LaTeX Client Controller
 * Generated by scripts/build_worker.mjs
 */`,
    },
  });

  const clientStat = fs.statSync(CLIENT_OUT);
  console.log(`✓ Client bundled: ${CLIENT_OUT} (${(clientStat.size / 1024).toFixed(1)} KB)`);

  // 3. Build UI Controller (ESM for browser DOM interaction)
  await esbuild.build({
    entryPoints: [UI_ENTRY],
    outfile: UI_OUT,
    bundle: true,
    format: 'esm',
    target: ['es2022'],
    minify: false,
    sourcemap: false,
    banner: {
      js: `/*
 * Word-to-LaTeX UI Controller
 * Generated by scripts/build_worker.mjs
 */`,
    },
  });

  const uiStat = fs.statSync(UI_OUT);
  console.log(`✓ UI bundled:     ${UI_OUT} (${(uiStat.size / 1024).toFixed(1)} KB)`);
} catch (err) {
  console.error('✗ Build failed:', err);
  process.exit(1);
}
